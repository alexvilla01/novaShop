-- V1: esquema inicial novaShop (portable PostgreSQL 15+ / H2 para pruebas)
CREATE TABLE categoria (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80)  NOT NULL UNIQUE,
    slug VARCHAR(90)  NOT NULL UNIQUE
);

CREATE TABLE producto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         VARCHAR(120) NOT NULL UNIQUE,
    name         VARCHAR(140) NOT NULL,
    description  VARCHAR(2000) NOT NULL,
    price_cents  INT          NOT NULL CHECK (price_cents > 0),
    stock        INT          NOT NULL CHECK (stock >= 0),
    origin       VARCHAR(16)  NOT NULL CHECK (origin IN ('PROPIO', 'DROPSHIPPING')),
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    category_id  BIGINT       NOT NULL REFERENCES categoria (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_producto_categoria_activa ON producto (category_id, is_active);

CREATE TABLE producto_imagen (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT       NOT NULL REFERENCES producto (id) ON DELETE CASCADE,
    url        VARCHAR(512) NOT NULL,
    position   INT          NOT NULL
);
CREATE INDEX idx_producto_imagen_producto ON producto_imagen (product_id, position);

CREATE TABLE orden (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT NOT NULL REFERENCES producto (id),
    product_name     VARCHAR(140) NOT NULL,
    unit_price_cents INT          NOT NULL,
    quantity         INT          NOT NULL CHECK (quantity > 0),
    channel          VARCHAR(16)  NOT NULL DEFAULT 'WHATSAPP',
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_orden_created_at ON orden (created_at DESC);
